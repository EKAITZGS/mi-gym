export const EX_BY_ID = Object.fromEntries(EXERCISES.map(e => [e.id, e]));

// Ejercicios propios del usuario (sin foto). Se sincronizan desde el estado de la app.
export function setCustomExercises(list = []) {
  for (let i = EXERCISES.length - 1; i >= 0; i--) {
    if (EXERCISES[i].custom) {
      delete EX_BY_ID[EXERCISES[i].id]
      EXERCISES.splice(i, 1)
    }
  }
  for (const c of list) {
    const e = { id: c.id, name: c.name, group: c.group, main: [c.group], sec: [], equip: 'Propio', imgs: [], custom: true }
    EXERCISES.push(e)
    EX_BY_ID[e.id] = e
  }
}
