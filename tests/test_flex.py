import os
import json
from playwright.sync_api import sync_playwright
errors=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=os.environ.get('CHROME') or None, args=['--no-sandbox'])
    pg=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,locale='es-ES').new_page()
    pg.on('pageerror',lambda e: errors.append(str(e)))
    pg.on('dialog', lambda d: d.accept())
    pg.goto('http://127.0.0.1:4173/'); pg.wait_for_selector('.tabbar')
    pg.click('.tabbar button:has-text("Entreno")')
    # 1) Día del plan: cambiar ejercicio 2, quitar el 4, añadir uno
    pg.click('.daycard:has-text("Pecho y tríceps") button:has-text("Empezar")')
    pg.wait_for_selector('text=Terminar entreno')
    pg.locator('.card').nth(1).locator('button.tool:has-text("Cambiar")').click()
    pg.click('.sheet .chip:has-text("Pecho")')
    pg.click('.sheet .row:has-text("Cruces en polea")'); pg.click('.sheet button:has-text("Añadir")')
    pg.locator('.card').nth(3).locator('button.tool:has-text("Quitar")').click()
    pg.locator('.card').nth(0).locator('button.tool:has-text("Serie")').click()
    pg.click('button:has-text("Añadir ejercicio")')
    pg.fill('.sheet input[placeholder="Buscar ejercicio…"]','Fondos (pecho)')
    pg.click('.sheet .row:has-text("Fondos (pecho)")'); pg.click('.sheet button:has-text("Añadir")')
    names=[pg.locator('.card').nth(i).locator('b').first.inner_text() for i in range(pg.locator('.card').count())]
    print('ejercicios sesión:', names)
    print('series ej1:', pg.locator('.card').nth(0).locator('.setrow:not(.drop)').count())
    pg.locator('.card').nth(1).locator('input.inp').nth(0).fill('15'); pg.locator('.card').nth(1).locator('input.inp').nth(1).fill('12')
    pg.screenshot(path='tests/shots/f1_session.png')
    pg.click('text=Terminar entreno'); pg.click('text=Saltar'); pg.wait_for_selector('text=Has cambiado ejercicios')
    pg.screenshot(path='tests/shots/f2_done.png')
    pg.click('text=Guardar cambios en el plan'); pg.click('text=Listo')
    d=json.loads(pg.evaluate("localStorage.getItem('migym.v1')"))
    print('plan pecho ahora:', [i['ex'] for i in d['plan'][0]['items']])
    print('sesión guardada:', list(d['sessions'][-1]['entries'].keys()), d['sessions'][-1]['dayName'])
    # 2) Entreno libre solo brazos
    pg.click('text=Entreno libre')
    pg.wait_for_selector('text=Añade los ejercicios')
    pg.click('button:has-text("Añadir ejercicio")'); pg.click('.sheet .chip:has-text("Bíceps")')
    pg.click('.sheet .row:has-text("Curl martillo")'); pg.click('.sheet button:has-text("Añadir")')
    pg.locator('.card').nth(0).locator('.chk').first.click()
    pg.locator('.card').nth(0).locator('input.inp').nth(0).fill('12'); pg.locator('.card').nth(0).locator('input.inp').nth(1).fill('10')
    pg.click('text=Terminar entreno'); pg.click('text=Saltar'); pg.wait_for_selector('text=Guardar como día nuevo')
    pg.click('text=Guardar como día nuevo'); pg.click('text=Listo')
    d=json.loads(pg.evaluate("localStorage.getItem('migym.v1')"))
    print('días:', [x['name'] for x in d['plan']], '| última sesión:', d['sessions'][-1]['dayName'], list(d['sessions'][-1]['entries']))
    b.close()
print('ERR',errors)
