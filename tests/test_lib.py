import os
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=os.environ.get('CHROME') or None, args=['--no-sandbox'])
    pg=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2).new_page(); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    imgs=[]; pg.on('request', lambda r: imgs.append(r.url) if '/ex/' in r.url else None)
    pg.goto('http://127.0.0.1:4173/'); pg.wait_for_selector('.tabbar')
    pg.click('.tabbar button:has-text("Entreno")'); pg.wait_for_timeout(300)
    pg.click('text=Entreno libre'); pg.wait_for_selector('text=Añade los ejercicios')
    pg.click('button:has-text("Añadir ejercicio")'); pg.wait_for_timeout(500)
    print('filas iniciales:', pg.locator('.sheet .list .row').count(), '| botón:', pg.locator('.more-btn').inner_text())
    print('fotos pedidas al abrir:', len(set(imgs)))
    pg.click('.more-btn'); pg.wait_for_timeout(200); print('tras ver más:', pg.locator('.sheet .list .row').count())
    pg.fill('.sheet input[placeholder="Buscar ejercicio…"]','inclinado smith'); pg.wait_for_timeout(200)
    print('busca "inclinado smith":', [x.inner_text().split('\n')[0] for x in pg.locator('.sheet .list .row').all()])
    pg.fill('.sheet input[placeholder="Buscar ejercicio…"]','gluteo'); pg.wait_for_timeout(200)
    print('busca "gluteo":', [x.inner_text().split('\n')[0] for x in pg.locator('.sheet .list .row').all()])
    pg.fill('.sheet input[placeholder="Buscar ejercicio…"]',''); pg.click('.sheet .chip:has-text("Antebrazo")'); pg.wait_for_timeout(200)
    print('antebrazo:', [x.inner_text().split('\n')[0] for x in pg.locator('.sheet .list .row').all()])
    pg.fill('.sheet input[placeholder="Buscar ejercicio…"]','press inclinado'); pg.click('.sheet .chip:has-text("Todos")'); pg.wait_for_timeout(200)
    pg.locator('.sheet .list .row:has-text("Smith")').first.click(); pg.wait_for_timeout(500)
    pg.locator('.sheet').last.screenshot(path='tests/shots/smith.png')
    print('ERR',errs)
